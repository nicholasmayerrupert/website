// Convert generated component atlases to small, registered native pixel parts.
import sharp from 'sharp';
import { writeFileSync } from 'node:fs';
import { cutFrame, makePalette } from './import-creature-art.mjs';
const dimensions = [[12,14,6,13],[13,14,7,0],[11,5,5,1],[5,8,2,1],[4,7,2,1],[7,5,2,1],[5,7,2,1],[4,6,2,1],[4,4,2,1],[11,21,10,0]];
const names=['head','torso','hips','thigh','shin','boot','upperArm','forearm','hand','cape'];
const sets=[];
for(const name of ['base','wayfarer','hedgeweaver','hearthguard']){
 const {data,info}=await sharp(`src/sand/art/player/${name}-grid-v2.png`).ensureAlpha().raw().toBuffer({resolveWithObject:true});
 const image={data,width:info.width,height:info.height};
 const parts=dimensions.map(([width,height,px,py],i)=>{
  const f=cutFrame(image,i%4,Math.floor(i/4));
  // Author color and transparency on half-cell samples within the shared rig coordinates.
  const gridWidth=Math.ceil(width/2),gridHeight=Math.ceil(height/2);
  // Register the base face's eye inside its logical sample cell.
  const samplePhase=name==='base'&&i===0?.7:.5;
  const pixels=Array.from({length:width*height},(_,at)=>{
   const x=Math.min(f.maxX,Math.floor(f.minX+(Math.floor(at%width/2)+samplePhase)*(f.maxX-f.minX+1)/gridWidth));
   const y=Math.min(f.maxY,Math.floor(f.minY+(Math.floor(Math.floor(at/width)/2)+samplePhase)*(f.maxY-f.minY+1)/gridHeight));
   return f.background[y*f.width+x]?null:f.pixels[y*f.width+x];
  });
  return {name:names[i],width,height,pivot:[px,py],pixels};
 });
 const {colors}=makePalette(parts.map(p=>p.pixels),12);
 for(const p of parts)p.pixels=p.pixels.map(rgb=>{
  if(!rgb)return 0;
  let best=0,d=Infinity;colors.forEach((c,i)=>{const n=c.reduce((s,v,k)=>s+(v-rgb[k])**2,0);if(n<d){best=i;d=n;}});
  const [r,g,b]=colors[best];return (0xff000000|(r<<16)|(g<<8)|b)>>>0;
 });
 sets.push({name,parts});
}
writeFileSync('src/sand/content/playerParts.js','// Generated by scripts/import-player-parts.mjs from art/player/*-grid-v2.png.\nexport default '+JSON.stringify(sets,null,2)+';\n');
console.log('Imported base components and three armor sets (10 registered parts each).');
