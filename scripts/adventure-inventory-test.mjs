import assert from 'node:assert/strict';
import { MISSION } from '../src/sand/wasmBridge/abi.generated.js';
import { initSandWasm, createEngineWasm, PLANET, MAT } from '../src/sand/wasmBridge/engineFactory.js';
await initSandWasm();
const e=createEngineWasm({cols:128,rows:100,planetId:PLANET.FRONTIER,sinksOn:false});
try {
 e.setSurvivalInventory(true);e.setCreatureRuntime(false,false);
 for(let x=1;x<127;x++)e.paintDisc(x,70,0,MAT.STONE,true);e.syncComponents();
 const id=e.spawnPlayer(50,62),inv=()=>e.getInventory(id),potion=320;
 e.startMission(MISSION.FRONTIER,id);
 const total=definition=>inv().slots.filter(s=>s.definitionId===definition).reduce((n,s)=>n+s.count,0);
 const before=total(potion);assert.ok(e.addGear(id,potion,20));
 assert.equal(total(potion),before+20);
 let index=inv().slots.findIndex(s=>s.definitionId===potion);
 assert.ok(inv().slots[index].count>1,'matching potions automatically stack');
 const count=inv().slots[index].count;
 e.inventoryCursorPick(id,index,true);
 assert.equal(e.getCursor(id).count,Math.ceil(count/2),'potions split with right-click');
 e.inventoryCursorPick(id,9,false);
 e.inventoryCursorPick(id,index,true);e.inventoryCursorPick(id,10,false);
 const quickbar=inv().slots.slice(0,9);
 e.inventorySort(id);
 assert.deepEqual(inv().slots.slice(0,9),quickbar,'sorting preserves every quickbar slot');
 assert.equal(inv().slots.slice(9).filter(s=>s.definitionId===potion).length,1,'sorting consolidates old potion stacks');
 assert.equal(total(potion),before+20);
 const armorBefore=total(100);assert.ok(e.addGear(id,100,2));
 assert.equal(total(100),armorBefore+2);
 assert.ok(inv().slots.filter(s=>s.definitionId===100).every(s=>s.count===1),'armor remains individual equipment');
 index=inv().slots.findIndex((s,i)=>i>=9&&s.definitionId===potion);
 e.inventoryCursorPick(id,index,false);const carried=e.getCursor(id).count;
 const beforeSort=inv();e.inventorySort(id);assert.deepEqual(inv(),beforeSort,'sorting is a no-op while carrying');
 assert.ok(e.throwFromCursor(id,false));assert.equal(e.getCursor(id).count,carried-1);
 assert.ok(e.throwFromCursor(id,true));assert.equal(e.getCursor(id),null);
 assert.equal(e.getItems().filter(s=>s.definitionId===potion).reduce((n,s)=>n+s.count,0),carried,'drops preserve definition and quantity');
 index=inv().slots.findIndex(s=>s.isTool);e.inventoryCursorPick(id,index,false);
 assert.equal(e.throwFromCursor(id,true),false,'mining tool stays protected');e.inventoryCursorPick(id,index,false);
 const kept=total(potion);for(let i=0;i<3;i++)assert.ok(e.addGear(id,potion,80));assert.equal(total(potion),kept+240);
 assert.ok(inv().slots.filter(s=>s.definitionId===potion).every(s=>s.count<=99),'potions overflow into stacks of at most 99');
 const slots=inv().slots,items=e.getItems();
 const saved=e.writeCheckpoint();assert.ok(e.readCheckpoint(saved),'stacked potions and dropped items survive checkpoints');
 assert.deepEqual(inv().slots,slots);assert.deepEqual(e.getItems(),items);
 console.log('ok: potion stacking, splitting, sorting, drops, protected tools, and checkpoint round-trip');
} finally {e.destroy();}
